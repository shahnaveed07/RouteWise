export function formatDistanceKm(distanceMeters) {
  if (typeof distanceMeters !== 'number' || !Number.isFinite(distanceMeters)) {
    return '0.0 km';
  }
  if (distanceMeters < 1000) {
    return `${Math.round(distanceMeters)} m`;
  }
  return `${(distanceMeters / 1000).toFixed(1)} km`;
}

export function formatDurationHuman(durationSeconds) {
  if (typeof durationSeconds !== 'number' || !Number.isFinite(durationSeconds)) {
    return '0 min';
  }
  const totalMinutes = Math.max(1, Math.round(durationSeconds / 60));
  if (totalMinutes < 60) {
    return `${totalMinutes} min`;
  }
  const hours = Math.floor(totalMinutes / 60);
  const mins = totalMinutes % 60;
  return mins > 0 ? `${hours} hr ${mins} min` : `${hours} hr`;
}

const PROFILE_LABELS = {
  'driving-car': 'Driving (Car)',
  'foot-walking': 'Walking (Foot)',
  'cycling-regular': 'Cycling (Regular)',
};

export function describeRouteSummaryState(route) {
  if (!route) {
    return null;
  }
  const isMock =
    Boolean(route.isMock) || route.source === 'LOCAL_E2E_MOCK';
  const attributionText = isMock
    ? 'Source: Local E2E Simulated Geometry (LOCAL_E2E_MOCK) — Not provided by openrouteservice'
    : typeof route.attribution === 'string'
    ? route.attribution
    : route.attribution?.text ||
      'Route directions by openrouteservice.org by HeiGIT';
  const attributionUrl = isMock
    ? null
    : typeof route.attribution === 'object' && route.attribution?.url
    ? route.attribution.url
    : 'https://openrouteservice.org/';

  return {
    isMock,
    source: route.source || (isMock ? 'LOCAL_E2E_MOCK' : 'OPENROUTESERVICE'),
    bannerHeading: isMock
      ? 'SIMULATED TEST ROUTE — NOT REAL ROAD DIRECTIONS'
      : null,
    distanceDisplay: isMock
      ? 'Simulated (Not Real Road Distance)'
      : formatDistanceKm(route.distanceMeters),
    durationDisplay: isMock
      ? 'Simulated (Not Real Travel Time)'
      : formatDurationHuman(route.durationSeconds),
    attributionText,
    attributionUrl,
  };
}

export default function RouteSummary({
  routeResult = null,
  routeError = null,
  dayLabel = 'Selected Day',
  onClearRoute,
}) {
  if (routeError) {
    return (
      <div
        className="route-summary-card route-summary-error"
        role="alert"
        data-testid="route-error-banner"
      >
        <div className="route-summary-header">
          <h3 className="route-summary-title">
            Route Calculation Unavailable ({dayLabel})
          </h3>
        </div>
        <p className="route-error-text">{routeError}</p>
      </div>
    );
  }

  if (!routeResult || !routeResult.route) {
    return null;
  }

  const { route } = routeResult;
  const stops = Array.isArray(route.stops) ? route.stops : [];
  const warnings = Array.isArray(route.warnings) ? route.warnings : [];
  const summaryState = describeRouteSummaryState(route);
  const isMock = summaryState.isMock;

  return (
    <div
      className={
        isMock
          ? 'route-summary-card route-summary-mock'
          : 'route-summary-card'
      }
      role="region"
      aria-label={`Calculated route summary for ${dayLabel}`}
      data-testid="route-summary-card"
      data-route-source={summaryState.source}
      data-route-mock={String(isMock)}
    >
      {isMock && (
        <div
          className="route-mock-banner"
          role="status"
          data-testid="mock-route-banner"
        >
          <strong>{summaryState.bannerHeading}</strong>
          <span>
            Generated by the local E2E test harness using straight-line stop coordinates. Actual road navigation distance and duration require a live openrouteservice calculation.
          </span>
        </div>
      )}

      <div className="route-summary-header">
        <div>
          <h3 className="route-summary-title">
            {isMock
              ? `Simulated Test Route — ${dayLabel}`
              : `Multi-Stop Route Summary — ${dayLabel}`}
          </h3>
          <span className="route-summary-subtitle">
            Profile: {PROFILE_LABELS[route.profile] || route.profile} •{' '}
            {stops.length} ordered stops • Source: {summaryState.source}
          </span>
        </div>
        {onClearRoute && (
          <button
            type="button"
            className="btn btn-secondary btn-xs"
            onClick={onClearRoute}
          >
            Clear Route Line
          </button>
        )}
      </div>

      <div className="route-metrics-grid">
        <div className="route-metric-box">
          <span className="route-metric-label">
            {isMock ? 'Road Distance Status' : 'Total Route Distance'}
          </span>
          <strong
            className="route-metric-value"
            data-testid="route-distance-value"
          >
            {summaryState.distanceDisplay}
          </strong>
        </div>
        <div className="route-metric-box">
          <span className="route-metric-label">
            {isMock ? 'Travel Time Status' : 'Estimated Travel Time'}
          </span>
          <strong
            className="route-metric-value"
            data-testid="route-duration-value"
          >
            {summaryState.durationDisplay}
          </strong>
        </div>
        <div className="route-metric-box">
          <span className="route-metric-label">Included Stops</span>
          <strong className="route-metric-value">{stops.length} Stops</strong>
        </div>
      </div>

      {warnings.length > 0 && (
        <div className="route-warning-box" role="status">
          {warnings.map((warningText, idx) => (
            <p key={idx} className="route-warning-text">
              Note: {warningText}
            </p>
          ))}
        </div>
      )}

      {stops.length > 0 && (
        <ol className="route-stops-sequence" aria-label="Ordered route stops">
          {stops.map((stop) => (
            <li key={stop.itemId} className="route-stop-pill">
              <span className="route-stop-num">{stop.stopNumber}</span>
              <span className="route-stop-name">
                {stop.title} ({stop.placeName})
              </span>
            </li>
          ))}
        </ol>
      )}

      <div
        className="route-attribution-note"
        data-testid="route-provider-attribution"
      >
        {summaryState.attributionUrl ? (
          <>
            <a
              href={summaryState.attributionUrl}
              target="_blank"
              rel="noopener noreferrer"
            >
              {summaryState.attributionText}
            </a>
          </>
        ) : (
          <span>{summaryState.attributionText}</span>
        )}
      </div>
    </div>
  );
}
